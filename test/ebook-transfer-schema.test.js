const { test } = require("node:test"), assert = require("node:assert/strict");
const fs = require("node:fs"), path = require("node:path");
const { PGlite } = require("@electric-sql/pglite");

test("temporary ebook schema isolates accounts, expires downloads and deletes metadata only after objects", async () => {
  const db = new PGlite();
  const a = "11111111-1111-4111-8111-111111111111", b = "22222222-2222-4222-8222-222222222222", id = "33333333-3333-4333-8333-333333333333";
  try {
    await db.exec(`create role anon; create role authenticated; create role service_role bypassrls;
      create schema auth; create table auth.users(id uuid primary key);
      create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
      grant usage on schema auth to authenticated; grant execute on function auth.uid() to authenticated;
      create schema storage;
      create table storage.buckets(id text primary key, name text, public boolean, file_size_limit bigint, allowed_mime_types text[]);
      create table storage.objects(bucket_id text, name text, created_at timestamptz default now(), primary key(bucket_id, name));
      alter table storage.objects enable row level security;
      grant usage on schema storage to authenticated; grant select, insert, delete on storage.objects to authenticated;
      create function storage.foldername(text) returns text[] language sql immutable as $$ select string_to_array($1, '/') $$;
      create function storage.allow_any_operation(text[]) returns boolean language sql stable as $$ select current_setting('storage.operation', true) = any($1) $$;`);
    await db.query("insert into auth.users values($1),($2)", [a, b]);
    const sql = fs.readFileSync(path.join(__dirname, "../supabase/migrations/202610230002_ebook_transfers.sql"), "utf8");
    await db.exec(sql); await db.exec(sql);
    await db.exec("set role anon");
    await assert.rejects(db.query("select * from public.reader_ebook_transfers"), /permission denied/);
    await assert.rejects(db.query("select * from public.reader_ebook_cleanup_candidates()"), /permission denied/);
    const user = async (who) => { await db.exec("reset role; set role authenticated"); await db.query("select set_config('request.jwt.claim.sub',$1,false)", [who]); };
    const operation = (name) => db.query("select set_config('storage.operation',$1,false)", [name]);
    const insert = () => db.query("insert into public.reader_ebook_transfers(id,sender_device,slug,title,bytes,sha256) values($1,$1,$2,'Test',100,$3)", [id, "ebook-" + "a".repeat(24), "b".repeat(64)]);
    const file = `${a}/${id}/book.zip`;
    await user(a); await insert();
    await assert.rejects(db.query("update public.reader_ebook_transfers set expires_at = now() + interval '1 year'"), /permission denied/);
    await assert.rejects(db.query("update public.reader_ebook_transfers set received_at = now()"), /permission denied/);
    await operation("object.upload");
    await db.query("insert into storage.objects(bucket_id,name) values('ebook-transfers',$1)", [file]);
    await operation("object.get_authenticated");
    assert.equal((await db.query("select * from storage.objects")).rows.length, 0, "incomplete upload downloadable");
    await db.query("update public.reader_ebook_transfers set ready=true where id=$1", [id]);
    assert.equal((await db.query("select * from storage.objects")).rows.length, 1);
    await operation("object.sign"); assert.equal((await db.query("select * from storage.objects")).rows.length, 0, "long-lived signed link allowed");
    await user(b); await operation("object.get_authenticated");
    assert.equal((await db.query("select * from public.reader_ebook_transfers")).rows.length, 0);
    assert.equal((await db.query("select * from storage.objects")).rows.length, 0);
    await assert.rejects(db.query("select public.reader_ebook_received($1)", [id]), /expired or unavailable/);
    await operation("object.upload"); await assert.rejects(db.query("insert into storage.objects(bucket_id,name) values('ebook-transfers',$1)", [`${a}/${id}/bad.zip`]), /row-level security/);
    await user(a); await operation("object.get_authenticated");
    await db.query("select public.reader_ebook_received($1)", [id]);
    assert.equal((await db.query("select * from storage.objects")).rows.length, 0, "received object still downloadable");
    await assert.rejects(db.query("select public.reader_ebook_forget($1)", [id]), /Remove the temporary object first/);
    await assert.rejects(db.query("delete from public.reader_ebook_transfers"), /permission denied/);
    await operation("object.delete_many");
    assert.equal((await db.query("delete from storage.objects where name=$1 returning name", [file])).rows.length, 1);
    await db.query("select public.reader_ebook_forget($1)", [id]);
    assert.equal((await db.query("select * from public.reader_ebook_transfers")).rows.length, 0);
    await insert(); await db.query("update public.reader_ebook_transfers set ready=true");
    await db.exec("reset role; update public.reader_ebook_transfers set expires_at=now()-interval '1 second'");
    await db.query("insert into storage.objects(bucket_id,name,created_at) values('ebook-transfers','orphan/book.zip',now()-interval '31 minutes')");
    await user(a); await operation("object.get_authenticated"); assert.equal((await db.query("select * from storage.objects")).rows.length, 0);
    await assert.rejects(db.query("select public.reader_ebook_received($1)", [id]), /expired or unavailable/);
    await assert.rejects(db.query("select * from public.reader_ebook_cleanup_candidates()"), /permission denied/);
    await db.exec("reset role; set role service_role");
    const candidates = (await db.query("select * from public.reader_ebook_cleanup_candidates()")).rows;
    assert.ok(candidates.some((r) => r.transfer_id === id)); assert.ok(candidates.some((r) => r.object_path === "orphan/book.zip"));
  } finally { await db.close(); }
});
